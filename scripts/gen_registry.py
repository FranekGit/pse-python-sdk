"""Generate ``src/pse_sdk/_registry.py`` from the PSE OpenAPI spec.

Usage::

    uv run scripts/gen_registry.py                      # regenerate
    uv run scripts/gen_registry.py --check              # exit 1 if out of date
    uv run scripts/gen_registry.py --spec openapi.json  # use a local spec file
"""

from __future__ import annotations

import argparse
import json
import string
import subprocess
import sys
import urllib.request
from pathlib import Path

SPEC_URL = "https://api.raporty.pse.pl/api/openapi"
OUTPUT = Path(__file__).resolve().parents[1] / "src" / "pse_sdk" / "_registry.py"

META_COLUMNS = (
    "dtime",
    "dtime_utc",
    "period",
    "period_utc",
    "business_date",
    "publication_ts",
    "publication_ts_utc",
)
DATE_COLUMN = "business_date"

TEMPLATE = string.Template("""\
# Generated by scripts/gen_registry.py from $url
# (spec version $version). Do not edit by hand.
from typing import Literal

from pse_sdk._endpoint_spec import EndpointSpec

Endpoint = Literal[$names]

REGISTRY: dict[Endpoint, EndpointSpec] = {$entries}
""")


def load_spec(source: str) -> dict:
    """Load the OpenAPI spec from a URL or a local file path."""
    if source.startswith(("http://", "https://")):
        with urllib.request.urlopen(source, timeout=60) as resp:
            return json.load(resp)
    return json.loads(Path(source).read_text(encoding="utf-8"))


def parse_keys(paths: dict) -> dict[str, tuple[str, ...]]:
    """Extract primary key columns from the by-key paths.

    ``/gen-jw/dtime_utc/{dtime_utc}/resource_code/{resource_code}``
    → ``{"gen-jw": ("dtime_utc", "resource_code")}``
    """
    keys: dict[str, tuple[str, ...]] = {}
    for path in paths:
        if "{" not in path:
            continue
        name, *parts = path.strip("/").split("/")
        keys[name] = tuple(parts[::2])
    return keys


def build_registry(spec: dict) -> dict[str, dict]:
    """Build a registry entry for every endpoint in *spec*, sorted by name."""
    keys = parse_keys(spec["paths"])
    registry: dict[str, dict] = {}
    for name, schema in sorted(spec["components"]["schemas"].items()):
        columns = {col: prop["type"] for col, prop in schema["properties"].items()}
        registry[name] = {
            "columns": columns,
            "date_column": DATE_COLUMN if DATE_COLUMN in columns else None,
            "meta_columns": tuple(c for c in META_COLUMNS if c in columns),
            "keys": keys.get(name, ()),
        }
    return registry


def render(registry: dict[str, dict], spec_version: str) -> str:
    """Render *registry* as the source code of ``_registry.py``.

    Values are written with ``repr`` and laid out by ``ruff format``; trailing
    commas keep one endpoint per line.
    """
    names = "".join(f"{name!r}," for name in registry)
    entries = "".join(
        f"{name!r}: EndpointSpec({_kwargs(entry)})," for name, entry in registry.items()
    )
    source = TEMPLATE.substitute(
        url=SPEC_URL, version=spec_version, names=names, entries=entries
    )
    return _ruff_format(source)


def _kwargs(entry: dict) -> str:
    return ", ".join(f"{field}={value!r}" for field, value in entry.items())


def _ruff_format(source: str) -> str:
    """Format *source* with the ruff pinned in ``uv.lock``, ignoring config."""
    result = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--isolated", "-"],
        input=source,
        capture_output=True,
        encoding="utf-8",
        check=True,
    )
    return result.stdout


def _check(source: str) -> int:
    """Return 1 if the committed registry differs from *source*, else 0."""
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None
    if current != source:
        print(
            f"{OUTPUT.name} is out of date. Run: uv run scripts/gen_registry.py",
            file=sys.stderr,
        )
        return 1
    print(f"{OUTPUT.name} is up to date.")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--spec",
        default=SPEC_URL,
        help="spec URL or local file path (default: %(default)s)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the committed registry is out of date",
    )
    args = parser.parse_args(argv)

    spec = load_spec(args.spec)
    registry = build_registry(spec)
    source = render(registry, spec["info"]["version"])

    if args.check:
        return _check(source)

    OUTPUT.write_text(source, encoding="utf-8", newline="\n")
    print(f"Wrote {len(registry)} endpoints to {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Generate ``src/pse_sdk/_registry.py`` from the PSE OpenAPI spec.

Usage::

    python scripts/gen_registry.py                      # regenerate
    python scripts/gen_registry.py --check              # exit 1 if out of date
    python scripts/gen_registry.py --spec openapi.json  # use a local spec file
"""

from __future__ import annotations

import argparse
import json
import sys
import urllib.request
from pathlib import Path

SPEC_URL = "https://api.raporty.pse.pl/api/openapi"
OUTPUT = Path(__file__).resolve().parents[1] / "src" / "pse_sdk" / "_registry.py"

META_COLUMNS = (
    "dtime",
    "dtime_utc",
    "period",
    "period_utc",
    "business_date",
    "publication_ts",
    "publication_ts_utc",
)
DATE_COLUMN = "business_date"

HEADER = '''\
# Generated by scripts/gen_registry.py from {url}
# (spec version {version}). Do not edit by hand.
from dataclasses import dataclass
from typing import Literal

ColumnType = Literal["string", "number", "integer", "boolean"]


@dataclass(frozen=True)
class EndpointSpec:
    """Schema of one PSE API endpoint."""

    columns: dict[str, ColumnType]  # all columns in API order -> JSON type
    date_column: str | None  # column for date-range filtering, None = no filter
    meta_columns: tuple[str, ...]  # dtime/period/business_date/publication_ts (+ _utc)
    keys: tuple[str, ...]  # primary key columns
'''


def load_spec(source: str) -> dict:
    """Load the OpenAPI spec from a URL or a local file path."""
    if source.startswith(("http://", "https://")):
        with urllib.request.urlopen(source, timeout=60) as resp:
            return json.load(resp)
    return json.loads(Path(source).read_text(encoding="utf-8"))


def parse_keys(paths: dict) -> dict[str, tuple[str, ...]]:
    """Extract primary key columns from the by-key paths.

    ``/gen-jw/dtime_utc/{dtime_utc}/resource_code/{resource_code}``
    → ``{"gen-jw": ("dtime_utc", "resource_code")}``
    """
    keys: dict[str, tuple[str, ...]] = {}
    for path in paths:
        if "{" not in path:
            continue
        name, *parts = path.strip("/").split("/")
        keys[name] = tuple(parts[::2])
    return keys


def build_registry(spec: dict) -> dict[str, dict]:
    """Build a registry entry for every endpoint in *spec*, sorted by name."""
    keys = parse_keys(spec["paths"])
    registry: dict[str, dict] = {}
    for name, schema in sorted(spec["components"]["schemas"].items()):
        columns = {col: prop["type"] for col, prop in schema["properties"].items()}
        registry[name] = {
            "columns": columns,
            "date_column": DATE_COLUMN if DATE_COLUMN in columns else None,
            "meta_columns": tuple(c for c in META_COLUMNS if c in columns),
            "keys": keys.get(name, ()),
        }
    return registry


def render(registry: dict[str, dict], spec_version: str) -> str:
    """Render *registry* as the source code of ``_registry.py``."""
    lines = [HEADER.format(url=SPEC_URL, version=spec_version), ""]

    lines.append("Endpoint = Literal[")
    lines += [f"    {_quote(name)}," for name in registry]
    lines += ["]", "", "REGISTRY: dict[Endpoint, EndpointSpec] = {"]

    for name, entry in registry.items():
        date_column = _quote(entry["date_column"]) if entry["date_column"] else "None"
        lines.append(f"    {_quote(name)}: EndpointSpec(")
        lines.append("        columns={")
        lines += [
            f"            {_quote(col)}: {_quote(type_)},"
            for col, type_ in entry["columns"].items()
        ]
        lines.append("        },")
        lines.append(f"        date_column={date_column},")
        lines += _render_tuple("meta_columns", entry["meta_columns"])
        lines += _render_tuple("keys", entry["keys"])
        lines.append("    ),")

    lines.append("}")
    return "\n".join(lines) + "\n"


def _render_tuple(field: str, items: tuple[str, ...]) -> list[str]:
    if not items:
        return [f"        {field}=(),"]
    return [
        f"        {field}=(",
        *(f"            {_quote(item)}," for item in items),
        "        ),",
    ]


def _quote(value: str) -> str:
    """Return *value* as a double-quoted Python string literal."""
    return json.dumps(value)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--spec",
        default=SPEC_URL,
        help="spec URL or local file path (default: %(default)s)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the committed registry is out of date",
    )
    args = parser.parse_args(argv)

    spec = load_spec(args.spec)
    registry = build_registry(spec)
    source = render(registry, spec["info"]["version"])

    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != source:
            print(
                f"{OUTPUT.name} is out of date. Run: python scripts/gen_registry.py",
                file=sys.stderr,
            )
            return 1
        print(f"{OUTPUT.name} is up to date.")
        return 0

    OUTPUT.write_text(source, encoding="utf-8", newline="\n")
    print(f"Wrote {len(registry)} endpoints to {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
